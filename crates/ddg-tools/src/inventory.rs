//! File inventory: sizes, magic bytes, hashes and an extension histogram.

use anyhow::Result;
use ddg_formats::sha256;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

pub struct Entry {
    pub rel: String,
    pub size: u64,
    pub magic: [u8; 8],
    pub sha256: String,
    /// The file is entirely zero bytes (e.g. lost to a truncated image).
    pub all_zero: bool,
}

fn walk(dir: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
    let mut entries: Vec<_> = std::fs::read_dir(dir)?.collect::<Result<_, _>>()?;
    entries.sort_by_key(|e| e.file_name());
    for e in entries {
        let p = e.path();
        if e.file_type()?.is_dir() {
            walk(&p, out)?;
        } else {
            out.push(p);
        }
    }
    Ok(())
}

pub fn collect(root: &Path) -> Result<Vec<Entry>> {
    let mut paths = Vec::new();
    walk(root, &mut paths)?;
    paths
        .into_iter()
        .map(|p| {
            let data = std::fs::read(&p)?;
            let mut magic = [0u8; 8];
            let n = data.len().min(8);
            magic[..n].copy_from_slice(&data[..n]);
            Ok(Entry {
                rel: p.strip_prefix(root)?.to_string_lossy().replace('\\', "/"),
                size: data.len() as u64,
                magic,
                sha256: sha256::to_hex(&sha256::sha256(&data)),
                all_zero: !data.is_empty() && data.iter().all(|&b| b == 0),
            })
        })
        .collect()
}

fn magic_ascii(m: &[u8; 8]) -> String {
    m.iter()
        .map(|&b| if b.is_ascii_graphic() { b as char } else { '.' })
        .collect()
}

pub fn print_inventory(root: &Path) -> Result<()> {
    let entries = collect(root)?;
    let mut hist: BTreeMap<String, (usize, u64)> = BTreeMap::new();
    let mut total = 0;
    println!(
        "| path | size | magic (hex) | magic | sha256 (prefix) | note |\n|---|---:|---|---|---|---|"
    );
    for e in &entries {
        let ext = Path::new(&e.rel)
            .extension()
            .map(|x| x.to_string_lossy().to_ascii_lowercase())
            .unwrap_or_else(|| "(none)".into());
        let h = hist.entry(ext).or_default();
        h.0 += 1;
        h.1 += e.size;
        total += e.size;
        println!(
            "| {} | {} | `{}` | `{}` | `{}` | {} |",
            e.rel,
            e.size,
            sha256::to_hex(&e.magic),
            magic_ascii(&e.magic),
            &e.sha256[..16],
            if e.all_zero { "ALL ZERO" } else { "" }
        );
    }
    println!("\n{} files, {} bytes\n", entries.len(), total);
    println!("| extension | files | bytes |\n|---|---:|---:|");
    for (ext, (n, bytes)) in hist {
        println!("| .{ext} | {n} | {bytes} |");
    }
    Ok(())
}

pub fn print_manifest(root: &Path, variant: &str) -> Result<()> {
    println!("# Generated by `ddg-tools manifest`. Hashes only — no game data.");
    println!("variant = {variant:?}\n");
    for e in collect(root)? {
        println!("[[file]]");
        println!("path = {:?}", e.rel);
        println!("size = {}", e.size);
        println!("sha256 = {:?}", e.sha256);
        if e.all_zero {
            println!("damaged = true");
        }
        println!();
    }
    Ok(())
}
